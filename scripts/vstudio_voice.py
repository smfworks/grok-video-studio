#!/usr/bin/env python3
"""Local narration with Piper TTS (rhasspy/piper 2023.11.14-2, MIT) and a public-domain-data voice.

  vstudio_voice.py local script.txt out.wav [--piper-dir /workspace/vstudio/piper] [--voice en_US-ljspeech-high] [--rate 1.0]

Writes a WAV, checks it with ffprobe, and returns JSON. No network, no cost, no caps needed (nothing is generated by a paid service).
"""
import argparse, json, subprocess, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from vstudio_media import probe

DEFAULT_DIR = "/workspace/vstudio/piper"
DEFAULT_VOICE = "en_US-ljspeech-high"


class VoiceError(Exception):
    pass


def paths(piper_dir, voice):
    d = Path(piper_dir)
    exe, model = d / "bin" / "piper", d / "voices" / f"{voice}.onnx"
    for p in (exe, model, Path(str(model) + ".json")):
        if not p.is_file():
            raise VoiceError(f"missing {p}; run the pinned setup install first")
    return exe, model


def local(text, out, piper_dir=DEFAULT_DIR, voice=DEFAULT_VOICE, rate=1.0, timeout=600):
    if not text or not text.strip():
        raise VoiceError("text required")
    if not 0.5 <= rate <= 2.0:
        raise VoiceError("rate must be 0.5-2.0")
    exe, model = paths(piper_dir, voice)
    out = Path(out); tmp = out.with_name(out.name + ".part.wav")
    # Piper's length_scale is inverse speed
    cmd = [str(exe), "-m", str(model), "-f", str(tmp), "--length_scale", f"{1.0 / rate:.3f}"]
    r = subprocess.run(cmd, input=text.strip() + "\n", capture_output=True, text=True, timeout=timeout)
    if r.returncode != 0 or not tmp.is_file():
        tmp.unlink(missing_ok=True)
        raise VoiceError(f"piper failed ({r.returncode}): {r.stderr.strip()[-300:]}")
    try:
        info = probe(tmp)
    except RuntimeError as e:
        tmp.unlink(missing_ok=True); raise VoiceError(f"piper output unreadable: {e}")
    if not info["audio"] or info["duration"] <= 0:
        tmp.unlink(missing_ok=True); raise VoiceError("piper output has no audio")
    tmp.replace(out)
    return {"out": str(out), "duration": round(info["duration"], 3), "sample_rate": info["audio"]["sample_rate"], "voice": voice}


def main(argv=None):
    ap = argparse.ArgumentParser(); sub = ap.add_subparsers(dest="cmd", required=True)
    l = sub.add_parser("local"); l.add_argument("text_file"); l.add_argument("out")
    l.add_argument("--piper-dir", default=DEFAULT_DIR); l.add_argument("--voice", default=DEFAULT_VOICE)
    l.add_argument("--rate", type=float, default=1.0)
    a = ap.parse_args(argv)
    try:
        r = local(Path(a.text_file).read_text(), a.out, a.piper_dir, a.voice, a.rate)
    except VoiceError as e:
        print(json.dumps({"ok": False, "error": str(e)})); return 1
    print(json.dumps({"ok": True, **r})); return 0


if __name__ == "__main__":
    sys.exit(main())
